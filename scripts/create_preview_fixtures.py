def metric(key, label, value):
    return {"key": key, "label": label, "value": value}


def packet(frame, time, protocol, summary, src, dst, **fields):
    return {"frame_number": frame, "time_offset_seconds": time, "scope_id": SCOPE,
            "protocol": protocol, "summary": summary, "source_ip": src,
            "destination_ip": dst, "captured_length": 60, **fields}


def write(name, data):
    report = AnalysisReport.model_validate(data)
    destination = ROOT / "frontend" / "fixtures" / name
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text(report.model_dump_json(indent=2) + "\n")
    return report.model_dump(mode="json")


